/**
 * Sprite's filled mode enumeration.
 */
export enum SpriteFilledMode {
  /** Fill horizontally. */
  Horizontal,
  /** Fill vertically. */
  Vertical,
  /** Fill radially over 90 degrees. */
  Radial90,
  /** Fill radially over 180 degrees. */
  Radial180,
  /** Fill radially over 360 degrees. */
  Radial360
}
