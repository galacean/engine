/**
 * Auto-generate `src/ShaderLibrary/index.ts` by scanning every `.glsl` under
 * `src/ShaderLibrary/`. The `includeKey` is the file path relative to that
 * directory (forward slashes), which matches the `Preprocessor` URL-resolved
 * key for `#include "X/Y.glsl"`.
 *
 * Run via `npm run prebuild` in the shader package.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "src", "ShaderLibrary");
const OUTPUT = path.join(ROOT, "index.ts");

function walk(dir, baseDir, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, baseDir, out);
    } else if (entry.name.endsWith(".glsl")) {
      const rel = path.relative(baseDir, full).split(path.sep).join("/");
      out.push(rel);
    }
  }
}

const files = [];
walk(ROOT, ROOT, files);
files.sort();

function identifierFor(rel) {
  // Replace any non-identifier char with `_` and prepend `_` if it starts with a digit.
  let id = rel.replace(/\.glsl$/, "").replace(/[^A-Za-z0-9_]/g, "_");
  if (/^[0-9]/.test(id)) id = "_" + id;
  return id;
}

const lines = [];
lines.push("// Auto-generated by scripts/generate-shader-library-index.js — do not edit.");
lines.push("// Source files are scanned from this directory; includeKey = path relative to ShaderLibrary/.");
lines.push("");

const ids = files.map(identifierFor);
files.forEach((rel, i) => {
  lines.push(`import ${ids[i]} from "./${rel}";`);
});

lines.push("");
lines.push("interface IShaderFragment {");
lines.push("  includeKey: string;");
lines.push("  source: string;");
lines.push("}");
lines.push("");
lines.push("const fragmentList: IShaderFragment[] = [");
files.forEach((rel, i) => {
  lines.push(`  { source: ${ids[i]}, includeKey: ${JSON.stringify(rel)} },`);
});
lines.push("];");
lines.push("");
lines.push("export { fragmentList };");
lines.push("");

fs.writeFileSync(OUTPUT, lines.join("\n"), "utf-8");
console.log(`[generate-shader-library-index] wrote ${files.length} entries → ${path.relative(process.cwd(), OUTPUT)}`);
