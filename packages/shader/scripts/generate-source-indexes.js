/**
 * Auto-generate two index files keyed by file path so the editor (and runtime
 * preprocessor) can treat both as path-addressed asset libraries:
 *
 *   src/ShaderLibrary/index.ts  — `shaderLibrary` array of every `.glsl` chunk
 *   src/Shaders/index.ts        — `shaders` array of every `.shader` source
 *
 * Both arrays carry the file path relative to `packages/shader/src/`, so each
 * entry's identity matches the path the user types in source code:
 *  - `#include "ShaderLibrary/Common/Common.glsl"` ↔ `shaderLibrary[i].includeKey`
 *  - `Shaders/PBR.shader` (editor asset path) ↔ `shaders[i].path`
 *
 * Run via `npm run gen:sources` in the shader package; wired into `precompile`.
 */
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "src");

function walk(dir, ext, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, ext, out);
    else if (entry.name.endsWith(ext)) out.push(full);
  }
}

function identifierFor(rel, ext) {
  let id = rel.replace(new RegExp(`\\${ext}$`), "").replace(/[^A-Za-z0-9_]/g, "_");
  if (/^[0-9]/.test(id)) id = "_" + id;
  return id;
}

function generateLibrary() {
  const ROOT = path.join(SRC, "ShaderLibrary");
  const OUTPUT = path.join(ROOT, "index.ts");
  const ext = ".glsl";

  const files = [];
  walk(ROOT, ext, files);
  files.sort();

  const importPaths = files.map((f) => path.relative(ROOT, f).split(path.sep).join("/"));
  const paths = files.map((f) => path.relative(SRC, f).split(path.sep).join("/"));
  const ids = importPaths.map((p) => identifierFor(p, ext));

  const lines = [];
  lines.push("// Auto-generated by scripts/generate-source-indexes.js — do not edit.");
  lines.push("// path is relative to packages/shader/src/ and matches the string used in `#include \"...\"`.");
  lines.push("");
  lines.push(`import type { IShaderSource } from "../Shaders";`);
  importPaths.forEach((rel, i) => lines.push(`import ${ids[i]} from "./${rel}";`));
  lines.push("");
  lines.push("// prettier-ignore");
  lines.push("export const shaderLibrary: IShaderSource[] = [");
  paths.forEach((p, i) => lines.push(`  { source: ${ids[i]}, path: ${JSON.stringify(p)} },`));
  lines.push("];");
  lines.push("");

  fs.writeFileSync(OUTPUT, lines.join("\n"), "utf-8");
  console.log(`[generate-source-indexes] wrote ${files.length} chunks → ${path.relative(process.cwd(), OUTPUT)}`);
}

function generateShaders() {
  const ROOT = path.join(SRC, "Shaders");
  const OUTPUT = path.join(ROOT, "index.ts");
  const ext = ".shader";

  const files = [];
  walk(ROOT, ext, files);
  files.sort();

  const importPaths = files.map((f) => path.relative(ROOT, f).split(path.sep).join("/"));
  const paths = files.map((f) => path.relative(SRC, f).split(path.sep).join("/"));
  const ids = importPaths.map((p) => identifierFor(p, ext));

  const lines = [];
  lines.push("// Auto-generated by scripts/generate-source-indexes.js — do not edit.");
  lines.push("// path is relative to packages/shader/src/ and matches the string used in `#include \"...\"`.");
  lines.push("");
  importPaths.forEach((rel, i) => lines.push(`import ${ids[i]} from "./${rel}";`));
  lines.push("");
  lines.push("export interface IShaderSource {");
  lines.push("  path: string;");
  lines.push("  source: string;");
  lines.push("}");
  lines.push("");
  lines.push("// prettier-ignore");
  lines.push("export const shaders: IShaderSource[] = [");
  paths.forEach((p, i) => lines.push(`  { source: ${ids[i]}, path: ${JSON.stringify(p)} },`));
  lines.push("];");
  lines.push("");

  fs.writeFileSync(OUTPUT, lines.join("\n"), "utf-8");
  console.log(`[generate-source-indexes] wrote ${files.length} shaders → ${path.relative(process.cwd(), OUTPUT)}`);
}

generateLibrary();
generateShaders();
