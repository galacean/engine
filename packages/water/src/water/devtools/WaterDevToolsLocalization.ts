export function getWaterDevToolsDisplayLabel(label: string): string {
  const translation = SIMPLIFIED_CHINESE_TERMS[label];
  return translation ? `${label}（${translation}）` : label;
}

export function getWaterDevToolsDisplayOptions(
  options: Readonly<Record<string, string | number>>
): Readonly<Record<string, string | number>> {
  const localized: Record<string, string | number> = {};
  for (const [label, value] of Object.entries(options)) {
    localized[getWaterDevToolsDisplayLabel(label)] = value;
  }
  return Object.freeze(localized);
}
