import ts from "typescript";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Extract the transitive type declarations from the actual command contract, not a second handwritten schema.
const entry = fileURLToPath(new URL("../native/WaterAPIContract.ts", import.meta.url));
const waterRoot = fileURLToPath(new URL("../", import.meta.url));
const output = fileURLToPath(new URL("../native/WaterAPIDeclarations.ts", import.meta.url));
const program = ts.createProgram([entry], { target: ts.ScriptTarget.ESNext, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, skipLibCheck: true });
const checker = program.getTypeChecker();
const printer = ts.createPrinter();
const declarations = new Map();
function collect(symbol) {
  if (!symbol) return;
  if (symbol.flags & ts.SymbolFlags.Alias) symbol = checker.getAliasedSymbol(symbol);
  for (let node of symbol.declarations ?? []) {
    if (ts.isEnumMember(node)) node = node.parent;
    const source = node.getSourceFile();
    if (!source.fileName.startsWith(waterRoot)) continue;
    if (!(ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node) || ts.isEnumDeclaration(node) || ts.isVariableDeclaration(node))) continue;
    const name = node.name.getText(source);
    if (declarations.has(name)) {
      if (declarations.get(name) !== node) throw new Error(`Ambiguous Water API type: ${name}`);
      continue;
    }
    declarations.set(name, node);
    function visit(child) {
      if (ts.isTypeReferenceNode(child)) collect(checker.getSymbolAtLocation(child.typeName));
      if (ts.isTypeQueryNode(child)) collect(checker.getSymbolAtLocation(child.exprName));
      if (ts.isExpressionWithTypeArguments(child)) collect(checker.getSymbolAtLocation(child.expression));
      ts.forEachChild(child, visit);
    }
    visit(node);
  }
}
const source = program.getSourceFile(entry);
for (const symbol of checker.getExportsOfModule(checker.getSymbolAtLocation(source))) collect(symbol);
const text = [...declarations.entries()].map(([name, node]) => ts.isVariableDeclaration(node)
  ? `export declare const ${name}: ${checker.typeToString(checker.getTypeAtLocation(node))};`
  : printer.printNode(ts.EmitHint.Unspecified, node, node.getSourceFile())).join("\n\n") +
  "\n\nexport declare namespace tools { namespace water { function execute(command: WaterCommand): Promise<WaterResult<unknown>>; } }\n";
const content = `// Generated by scripts/generate-native-api.mjs. Do not edit.\nexport const WATER_API_DECLARATION = ${JSON.stringify(text)};\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== content) throw new Error("Water API declarations are stale. Run water:native-api:generate.");
} else {
  writeFileSync(output, content);
  if (process.env.WORLD_GALLERY_SOURCE_ROOT) writeFileSync(resolve(process.env.WORLD_GALLERY_SOURCE_ROOT, "shared/water/native/WaterAPIDeclarations.ts"), content);
}
console.log(`Water API: ${declarations.size} declarations ${process.argv.includes("--check") ? "verified" : "generated"}.`);
