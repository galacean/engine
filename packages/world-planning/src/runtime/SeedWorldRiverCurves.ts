import { RIVER_LIMITS, evaluateRiverCubicBezier } from "@galacean/engine-water/water/index";
import type { SeedWorldRiverReach } from "../world/SeedWorldPlanner.ts";

const RIVER_FIELD_SAMPLE_SPACING_METRES = 6;
const RIVER_BANK_TRANSITION_METRES = 10;
const MAXIMUM_HANDLE_FRACTION = 0.45;

/** One planar Bézier handle stored as a normalized local offset. */
export type SeedWorldRiverCurveHandle = readonly [number, number];

/** One canonical river anchor shared by terrain-field and Water compilation. */
export interface SeedWorldRiverCurveControlPoint {
  /** Stable identity retained from the semantic drainage reach. */
  readonly id: string;
  /** Normalized world X coordinate. */
  readonly x: number;
  /** Normalized world Z coordinate. */
  readonly y: number;
  /** Full water-surface width in metres. */
  readonly widthMetres: number;
  /** Terrain erosion depth in metres at this anchor. */
  readonly depthMetres: number;
  /** Dry-bank transition distance in metres at this anchor. */
  readonly bankFeatherMetres: number;
  /** Normalized upstream accumulation at this point. */
  readonly flow: number;
  /** Authoritative terrain-bed elevation at this anchor in world metres. */
  readonly bedElevationMetres: number;
  /** Incoming local Bézier handle in normalized world units. */
  readonly in: SeedWorldRiverCurveHandle;
  /** Outgoing local Bézier handle in normalized world units. */
  readonly out: SeedWorldRiverCurveHandle;
}

/** One continuous, downhill semantic reach represented as a smooth planar curve. */
export interface SeedWorldRiverCurve {
  /** Stable reach identity. */
  readonly id: string;
  /** Ordered upstream-to-downstream curve anchors. */
  readonly controls: readonly SeedWorldRiverCurveControlPoint[];
}

/** One rasterized continuous-river field at a caller-defined sample lattice. */
export interface SeedWorldRiverField {
  /** Smooth channel-and-bank influence in the inclusive range 0–1. */
  readonly channel: Float32Array;
  /** Signed distance in metres to the expanded bank boundary; negative values are inside. */
  readonly bankDistanceMetres: Float32Array;
  /** Accumulation sampled from the river reach with the strongest local influence. */
  readonly flow: Float32Array;
  /** Terrain erosion depth sampled from the same owning curve segment. */
  readonly depthMetres: Float32Array;
  /** Dry-bank transition sampled from the same owning curve segment. */
  readonly bankFeatherMetres: Float32Array;
  /** Binary water-surface ownership inside the authored river width. */
  readonly water: Uint8Array;
  /** Authoritative bed elevation from the nearest owning curve segment. */
  readonly bedElevationMetres: Float32Array;
  /** Along-reach arc length associated with the nearest owning curve segment. */
  readonly arcMetres: Float32Array;
  /** World-metre distance to the centreline of the nearest owning curve segment. */
  readonly centreDistanceMetres: Float32Array;
}

/** Minimal high-resolution river-bed field used only while encoding Hfinal. */
export interface SeedWorldRiverBedField {
  /** Smooth channel-and-bank influence in the inclusive range 0–1. */
  readonly channel: Float32Array;
  /** Authoritative bed elevation from the nearest owning curve segment. */
  readonly bedElevationMetres: Float32Array;
}

/** Sampling settings for one world-aligned river field. */
export interface SeedWorldRiverRasterOptions {
  /** Number of samples along each square field axis. */
  readonly resolution: number;
  /** Physical world width and height represented by the field. */
  readonly sizeMetres: number;
  /** Fractional sample offset: 0 for vertices, 0.5 for texel centers. */
  readonly sampleOffset?: number;
  /** Extra radial coverage beyond the physical channel bank, used only by a dependent renderer. */
  readonly bankExpansionMetres?: number;
  /** Positive-distance margin emitted outside the expanded bank for downstream smoothing. */
  readonly distanceFieldMarginMetres?: number;
  /** Optional curve chord used by a high-resolution baked field; defaults to the planning/Water spacing. */
  readonly curveSampleSpacingMetres?: number;
  /** Optional samples compiled once from `curves`; downstream rasters reuse these exact segments. */
  readonly curveSamples?: readonly (readonly SeedWorldRiverCurveSample[])[];
}

/** Minimal semantic drainage input required to compile canonical river curves. */
export interface SeedWorldRiverCurveSource {
  /** Physical world width and height represented by the reaches. */
  readonly sizeMetres: number;
  /** Ordered semantic reaches generated by hydrology. */
  readonly rivers: readonly SeedWorldRiverReach[];
}

/**
 * Converts drainage-cell reaches into a bounded set of smooth semantic curves.
 * @param plan Authoritative source-to-outlet drainage plan.
 * @returns Curves whose controls satisfy the Water authoring budget.
 * @throws {RangeError} When preserved junctions exceed the Water control-point budget.
 */
export function compileSeedWorldRiverCurves(plan: SeedWorldRiverCurveSource): readonly SeedWorldRiverCurve[] {
  const maximumDischarge = plan.rivers.reduce(
    (maximum, reach) => Math.max(maximum, ...reach.points.map((point) => point.discharge)),
    0
  );
  return Object.freeze(
    plan.rivers
      .filter((reach) => reach.points.length >= RIVER_LIMITS.minPointCount)
      .map((reach) => compileSeedWorldRiverCurve(reach, maximumDischarge, plan.sizeMetres))
  );
}

/**
 * Rasterizes smooth channel, flow, and water ownership fields from canonical river curves.
 * @param curves Canonical planner curves generated from the same Root Seed as terrain.
 * @param options World-aligned field resolution and sample placement.
 * @returns Continuous local fields without materializing any persistent texture assets.
 * @throws {RangeError} When field resolution, world size, sample offset, or margins are invalid.
 */
export function rasterizeSeedWorldRiverField(
  curves: readonly SeedWorldRiverCurve[],
  options: SeedWorldRiverRasterOptions
): SeedWorldRiverField {
  validateRasterOptions(options);
  const sampleOffset = options.sampleOffset ?? 0;
  const bankExpansionMetres = options.bankExpansionMetres ?? 0;
  const distanceFieldMarginMetres = options.distanceFieldMarginMetres ?? 0;
  const curveSampleSpacingMetres = options.curveSampleSpacingMetres ?? RIVER_FIELD_SAMPLE_SPACING_METRES;
  if (options.curveSamples && options.curveSamples.length !== curves.length) {
    throw new RangeError("Seed World river samples must match the canonical curve array.");
  }
  const channel = new Float32Array(options.resolution * options.resolution);
  const bankDistanceMetres = new Float32Array(options.resolution * options.resolution);
  bankDistanceMetres.fill(Number.POSITIVE_INFINITY);
  const flow = new Float32Array(options.resolution * options.resolution);
  const depthMetres = new Float32Array(options.resolution * options.resolution);
  const bankFeatherMetres = new Float32Array(options.resolution * options.resolution);
  const water = new Uint8Array(options.resolution * options.resolution);
  const bedElevationMetres = new Float32Array(options.resolution * options.resolution);
  const arcMetres = new Float32Array(options.resolution * options.resolution);
  const centreDistanceMetres = new Float32Array(options.resolution * options.resolution);
  centreDistanceMetres.fill(Number.POSITIVE_INFINITY);
  const sampleDenominator = options.resolution - 1 + sampleOffset * 2;
  const sampleSpacing = options.sizeMetres / sampleDenominator;
  for (let curveIndex = 0; curveIndex < curves.length; curveIndex++) {
    const curve = curves[curveIndex]!;
    const samples =
      options.curveSamples?.[curveIndex] ??
      sampleSeedWorldRiverCurve(curve, options.sizeMetres, curveSampleSpacingMetres);
    for (let index = 1; index < samples.length; index++) {
      rasterizeRiverSegment(
        channel,
        bankDistanceMetres,
        flow,
        depthMetres,
        bankFeatherMetres,
        water,
        bedElevationMetres,
        arcMetres,
        centreDistanceMetres,
        samples[index - 1],
        samples[index],
        {
          resolution: options.resolution,
          sizeMetres: options.sizeMetres,
          sampleOffset,
          sampleSpacing,
          bankExpansionMetres,
          distanceFieldMarginMetres
        }
      );
    }
  }
  return {
    channel,
    bankDistanceMetres,
    flow,
    depthMetres,
    bankFeatherMetres,
    water,
    bedElevationMetres,
    arcMetres,
    centreDistanceMetres
  };
}

/**
 * Rasterizes the canonical logical river bed for water tooling and hydrology diagnostics.
 * @remarks This field does not excavate Hfinal; wetland terrain is shaped only by its continuous basin SDF.
 * @param curves Canonical planner curves generated from the same Root Seed as terrain.
 * @param options World-aligned field resolution and sample placement.
 * @returns Channel influence and authoritative bed elevation without allocating unrelated process rasters.
 * @throws {RangeError} When field resolution, world size, or sample offset is invalid.
 */
export function rasterizeSeedWorldRiverBedField(
  curves: readonly SeedWorldRiverCurve[],
  options: Pick<SeedWorldRiverRasterOptions, "resolution" | "sizeMetres" | "sampleOffset">
): SeedWorldRiverBedField {
  validateRasterOptions(options);
  const sampleOffset = options.sampleOffset ?? 0;
  const channel = new Float32Array(options.resolution * options.resolution);
  const bedElevationMetres = new Float32Array(options.resolution * options.resolution);
  const centreDistanceMetres = new Float32Array(options.resolution * options.resolution);
  centreDistanceMetres.fill(Number.POSITIVE_INFINITY);
  const sampleDenominator = options.resolution - 1 + sampleOffset * 2;
  const sampleSpacing = options.sizeMetres / sampleDenominator;
  for (const curve of curves) {
    const samples = sampleSeedWorldRiverCurve(curve, options.sizeMetres, RIVER_FIELD_SAMPLE_SPACING_METRES);
    for (let index = 1; index < samples.length; index++) {
      rasterizeRiverBedSegment(channel, bedElevationMetres, centreDistanceMetres, samples[index - 1], samples[index], {
        resolution: options.resolution,
        sizeMetres: options.sizeMetres,
        sampleOffset,
        sampleSpacing,
        bankExpansionMetres: 0,
        distanceFieldMarginMetres: 0
      });
    }
  }
  return { channel, bedElevationMetres };
}

/**
 * Samples one canonical curve into short planar segments that preserve its authored Bézier path.
 * @param curve Canonical curve to sample.
 * @param sizeMetres Physical world size used to convert normalized coordinates.
 * @param spacingMetres Maximum approximate longitudinal spacing between samples.
 * @returns Ordered world-space samples with interpolated width, flow, bed elevation, and arc length.
 * @throws {RangeError} When sample spacing is not positive.
 */
export function sampleSeedWorldRiverCurve(
  curve: SeedWorldRiverCurve,
  sizeMetres: number,
  spacingMetres = RIVER_FIELD_SAMPLE_SPACING_METRES
): readonly SeedWorldRiverCurveSample[] {
  if (curve.controls.length < RIVER_LIMITS.minPointCount) return Object.freeze([]);
  if (!Number.isFinite(spacingMetres) || spacingMetres <= 0) {
    throw new RangeError("Seed World river sample spacing must be positive.");
  }
  const samples: SeedWorldRiverCurveSample[] = [];
  let arcMetres = 0;
  let previous: SeedWorldRiverCurveSample | undefined;
  for (let index = 0; index < curve.controls.length - 1; index++) {
    const start = curve.controls[index];
    const end = curve.controls[index + 1];
    const intervalCount = Math.max(1, Math.ceil(estimateBezierLength(start, end, sizeMetres) / spacingMetres));
    for (let step = index === 0 ? 0 : 1; step <= intervalCount; step++) {
      const raw = sampleBezierCurvePoint(start, end, step / intervalCount, sizeMetres);
      if (previous) arcMetres += Math.hypot(raw.x - previous.x, raw.z - previous.z);
      const sample = Object.freeze({ ...raw, arcMetres });
      samples.push(sample);
      previous = sample;
    }
  }
  return Object.freeze(samples);
}

/** One sampled point on a canonical river curve in world metres. */
export interface SeedWorldRiverCurveSample {
  /** World-space horizontal X coordinate. */
  readonly x: number;
  /** World-space horizontal Z coordinate. */
  readonly z: number;
  /** Full water-surface width in metres. */
  readonly widthMetres: number;
  /** Normalized upstream accumulation. */
  readonly flow: number;
  /** Terrain erosion depth in metres. */
  readonly depthMetres: number;
  /** Dry-bank transition distance in metres. */
  readonly bankFeatherMetres: number;
  /** Authoritative river-bed elevation in world metres. */
  readonly bedElevationMetres: number;
  /** Distance along this reach from its first control in world metres. */
  readonly arcMetres: number;
}

interface SeedWorldRiverCurveCandidate {
  readonly id: string;
  readonly x: number;
  readonly y: number;
  readonly elevation: number;
  readonly widthMetres: number;
  readonly flow: number;
  readonly depthMetres: number;
  readonly bankFeatherMetres: number;
  readonly bedElevationMetres: number;
  readonly junction: boolean;
}

interface RiverSegmentRasterOptions {
  readonly resolution: number;
  readonly sizeMetres: number;
  readonly sampleOffset: number;
  readonly sampleSpacing: number;
  readonly bankExpansionMetres: number;
  readonly distanceFieldMarginMetres: number;
}

function compileSeedWorldRiverCurve(
  reach: SeedWorldRiverReach,
  maximumDischarge: number,
  sizeMetres: number
): SeedWorldRiverCurve {
  const candidates: readonly SeedWorldRiverCurveCandidate[] = reach.points.map((point, index) => ({
    id: `${reach.id}-${index}`,
    x: point.x,
    y: point.y,
    elevation: point.elevation,
    widthMetres: point.widthMetres,
    flow: maximumDischarge > 0 ? clamp01(point.discharge / maximumDischarge) : 0,
    depthMetres: point.depthMetres,
    bankFeatherMetres: point.bankFeatherMetres,
    bedElevationMetres: point.bedElevationMetres,
    junction: point.junction === true
  }));
  const selected = candidates;
  return {
    id: reach.id,
    controls: Object.freeze(createBezierControls(selected))
  };
}

function createBezierControls(
  points: readonly SeedWorldRiverCurveCandidate[]
): readonly SeedWorldRiverCurveControlPoint[] {
  return points.map((point, index) => {
    const previous = points[Math.max(0, index - 1)];
    const next = points[Math.min(points.length - 1, index + 1)];
    const maximumHandleLength =
      index === 0
        ? normalizedDistance(point, next) * MAXIMUM_HANDLE_FRACTION
        : index === points.length - 1
          ? normalizedDistance(previous, point) * MAXIMUM_HANDLE_FRACTION
          : Math.min(normalizedDistance(previous, point), normalizedDistance(point, next)) * MAXIMUM_HANDLE_FRACTION;
    const incoming: SeedWorldRiverCurveHandle =
      index === 0
        ? [0, 0]
        : index === points.length - 1
          ? [(previous.x - point.x) / 3, (previous.y - point.y) / 3]
          : [(previous.x - next.x) / 6, (previous.y - next.y) / 6];
    const outgoing: SeedWorldRiverCurveHandle =
      index === points.length - 1
        ? [0, 0]
        : index === 0
          ? [(next.x - point.x) / 3, (next.y - point.y) / 3]
          : [(next.x - previous.x) / 6, (next.y - previous.y) / 6];
    const limitedIncoming = limitHandle(incoming, maximumHandleLength);
    const limitedOutgoing = limitHandle(outgoing, maximumHandleLength);
    return {
      id: point.id,
      x: point.x,
      y: point.y,
      widthMetres: point.widthMetres,
      flow: point.flow,
      depthMetres: point.depthMetres,
      bankFeatherMetres: point.bankFeatherMetres,
      bedElevationMetres: point.bedElevationMetres,
      in: boundHandleToWorld(point, limitedIncoming),
      out: boundHandleToWorld(point, limitedOutgoing)
    };
  });
}

function sampleBezierCurvePoint(
  start: SeedWorldRiverCurveControlPoint,
  end: SeedWorldRiverCurveControlPoint,
  t: number,
  sizeMetres: number
): SeedWorldRiverCurveSample {
  const controlX = start.x + start.out[0];
  const controlY = start.y + start.out[1];
  const endControlX = end.x + end.in[0];
  const endControlY = end.y + end.in[1];
  const point = evaluateRiverCubicBezier(
    { x: start.x, y: 0, z: start.y },
    { x: controlX, y: 0, z: controlY },
    { x: endControlX, y: 0, z: endControlY },
    { x: end.x, y: 0, z: end.y },
    t
  );
  const x = point.x,
    y = point.z;
  return {
    x: x * sizeMetres - sizeMetres * 0.5,
    z: y * sizeMetres - sizeMetres * 0.5,
    widthMetres: mix(start.widthMetres, end.widthMetres, t),
    flow: mix(start.flow, end.flow, t),
    depthMetres: mix(start.depthMetres, end.depthMetres, t),
    bankFeatherMetres: mix(start.bankFeatherMetres, end.bankFeatherMetres, t),
    bedElevationMetres: mix(start.bedElevationMetres, end.bedElevationMetres, t),
    arcMetres: 0
  };
}

function estimateBezierLength(
  start: SeedWorldRiverCurveControlPoint,
  end: SeedWorldRiverCurveControlPoint,
  sizeMetres: number
): number {
  let length = 0;
  let previous = sampleBezierCurvePoint(start, end, 0, sizeMetres);
  for (let step = 1; step <= 8; step++) {
    const current = sampleBezierCurvePoint(start, end, step / 8, sizeMetres);
    length += Math.hypot(current.x - previous.x, current.z - previous.z);
    previous = current;
  }
  return length;
}

function rasterizeRiverSegment(
  channel: Float32Array,
  bankDistanceMetres: Float32Array,
  flow: Float32Array,
  depthMetres: Float32Array,
  bankFeatherMetres: Float32Array,
  water: Uint8Array,
  bedElevationMetres: Float32Array,
  arcMetres: Float32Array,
  centreDistanceMetres: Float32Array,
  start: SeedWorldRiverCurveSample,
  end: SeedWorldRiverCurveSample,
  options: RiverSegmentRasterOptions
): void {
  const maximumBankRadius =
    Math.max(
      seedWorldRiverBankRadius(start.widthMetres, start.bankFeatherMetres),
      seedWorldRiverBankRadius(end.widthMetres, end.bankFeatherMetres)
    ) +
    options.bankExpansionMetres +
    options.distanceFieldMarginMetres;
  const minimumX = Math.min(start.x, end.x) - maximumBankRadius;
  const maximumX = Math.max(start.x, end.x) + maximumBankRadius;
  const minimumZ = Math.min(start.z, end.z) - maximumBankRadius;
  const maximumZ = Math.max(start.z, end.z) + maximumBankRadius;
  const startX = worldToLowerSampleIndex(minimumX, options);
  const endX = worldToUpperSampleIndex(maximumX, options);
  const startZ = worldToLowerSampleIndex(minimumZ, options);
  const endZ = worldToUpperSampleIndex(maximumZ, options);
  if (startX > endX || startZ > endZ) return;
  const directionX = end.x - start.x;
  const directionZ = end.z - start.z;
  const lengthSquared = directionX * directionX + directionZ * directionZ;
  for (let z = startZ; z <= endZ; z++) {
    const worldZ = sampleIndexToWorld(z, options);
    for (let x = startX; x <= endX; x++) {
      const worldX = sampleIndexToWorld(x, options);
      const t =
        lengthSquared > 0
          ? clamp(((worldX - start.x) * directionX + (worldZ - start.z) * directionZ) / lengthSquared, 0, 1)
          : 0;
      const nearestX = mix(start.x, end.x, t);
      const nearestZ = mix(start.z, end.z, t);
      const distance = Math.hypot(worldX - nearestX, worldZ - nearestZ);
      const width = mix(start.widthMetres, end.widthMetres, t);
      const riverBankFeatherMetres = mix(start.bankFeatherMetres, end.bankFeatherMetres, t);
      const waterBankRadius = width * 0.5 + options.bankExpansionMetres;
      const riverBankRadius = seedWorldRiverBankRadius(width, riverBankFeatherMetres);
      const riverFlow = mix(start.flow, end.flow, t);
      const riverDepthMetres = mix(start.depthMetres, end.depthMetres, t);
      const fieldIndex = z * options.resolution + x;
      const signedBankDistanceMetres = distance - waterBankRadius;
      if (signedBankDistanceMetres < bankDistanceMetres[fieldIndex]) {
        bankDistanceMetres[fieldIndex] = signedBankDistanceMetres;
        bankFeatherMetres[fieldIndex] = riverBankFeatherMetres;
      }
      if (distance > riverBankRadius) continue;
      const influence = 1 - smoothstep(width * 0.5, riverBankRadius, distance);
      const ownsSample =
        influence > channel[fieldIndex] + Number.EPSILON ||
        (influence >= channel[fieldIndex] - Number.EPSILON && distance < centreDistanceMetres[fieldIndex]);
      if (ownsSample) {
        channel[fieldIndex] = influence;
        flow[fieldIndex] = riverFlow;
        depthMetres[fieldIndex] = riverDepthMetres;
        bedElevationMetres[fieldIndex] = mix(start.bedElevationMetres, end.bedElevationMetres, t);
        arcMetres[fieldIndex] = mix(start.arcMetres, end.arcMetres, t);
        centreDistanceMetres[fieldIndex] = distance;
      }
      if (distance <= width * 0.5) water[fieldIndex] = 255;
    }
  }
}

function rasterizeRiverBedSegment(
  channel: Float32Array,
  bedElevationMetres: Float32Array,
  centreDistanceMetres: Float32Array,
  start: SeedWorldRiverCurveSample,
  end: SeedWorldRiverCurveSample,
  options: RiverSegmentRasterOptions
): void {
  const maximumBankRadius = Math.max(
    seedWorldRiverBankRadius(start.widthMetres, start.bankFeatherMetres),
    seedWorldRiverBankRadius(end.widthMetres, end.bankFeatherMetres)
  );
  const startX = worldToLowerSampleIndex(Math.min(start.x, end.x) - maximumBankRadius, options);
  const endX = worldToUpperSampleIndex(Math.max(start.x, end.x) + maximumBankRadius, options);
  const startZ = worldToLowerSampleIndex(Math.min(start.z, end.z) - maximumBankRadius, options);
  const endZ = worldToUpperSampleIndex(Math.max(start.z, end.z) + maximumBankRadius, options);
  const directionX = end.x - start.x;
  const directionZ = end.z - start.z;
  const lengthSquared = directionX * directionX + directionZ * directionZ;
  for (let z = startZ; z <= endZ; z++) {
    const worldZ = sampleIndexToWorld(z, options);
    for (let x = startX; x <= endX; x++) {
      const worldX = sampleIndexToWorld(x, options);
      const progress =
        lengthSquared > 0
          ? clamp(((worldX - start.x) * directionX + (worldZ - start.z) * directionZ) / lengthSquared, 0, 1)
          : 0;
      const distance = Math.hypot(worldX - mix(start.x, end.x, progress), worldZ - mix(start.z, end.z, progress));
      const width = mix(start.widthMetres, end.widthMetres, progress);
      const bankRadius = seedWorldRiverBankRadius(width, mix(start.bankFeatherMetres, end.bankFeatherMetres, progress));
      if (distance > bankRadius) continue;
      const fullBedRadius = Math.min(bankRadius * 0.7, Math.max(width * 0.5, options.sampleSpacing * Math.SQRT2));
      const influence = 1 - smoothstep(fullBedRadius, bankRadius, distance);
      const fieldIndex = z * options.resolution + x;
      const bed = mix(start.bedElevationMetres, end.bedElevationMetres, progress);
      const ownsSample =
        influence > channel[fieldIndex] + Number.EPSILON ||
        (influence >= channel[fieldIndex] - Number.EPSILON && distance < centreDistanceMetres[fieldIndex]);
      if (ownsSample) {
        channel[fieldIndex] = influence;
        bedElevationMetres[fieldIndex] = bed;
        centreDistanceMetres[fieldIndex] = distance;
      }
    }
  }
}

function validateRasterOptions(options: SeedWorldRiverRasterOptions): void {
  if (!Number.isInteger(options.resolution) || options.resolution < 2) {
    throw new RangeError("Seed World river fields require at least two samples per axis.");
  }
  if (!Number.isFinite(options.sizeMetres) || options.sizeMetres <= 0) {
    throw new RangeError("Seed World river fields require a positive world size.");
  }
  const sampleOffset = options.sampleOffset ?? 0;
  if (!Number.isFinite(sampleOffset) || sampleOffset < 0 || sampleOffset >= 1) {
    throw new RangeError("Seed World river field sample offset must be in [0, 1).");
  }
  const bankExpansionMetres = options.bankExpansionMetres ?? 0;
  if (!Number.isFinite(bankExpansionMetres) || bankExpansionMetres < 0) {
    throw new RangeError("Seed World river field bank expansion must be finite and non-negative.");
  }
  const distanceFieldMarginMetres = options.distanceFieldMarginMetres ?? 0;
  if (!Number.isFinite(distanceFieldMarginMetres) || distanceFieldMarginMetres < 0) {
    throw new RangeError("Seed World river distance-field margin must be finite and non-negative.");
  }
  const curveSampleSpacingMetres = options.curveSampleSpacingMetres ?? RIVER_FIELD_SAMPLE_SPACING_METRES;
  if (!Number.isFinite(curveSampleSpacingMetres) || curveSampleSpacingMetres <= 0) {
    throw new RangeError("Seed World river curve sample spacing must be positive.");
  }
}

/**
 * Returns the terrain influence radius required to blend one water width into its dry bank.
 * @param widthMetres Full water-surface width in metres.
 * @param bankFeatherMetres Dry-bank transition distance in metres.
 * @returns Radial channel-and-bank influence extent in metres.
 */
export function seedWorldRiverBankRadius(
  widthMetres: number,
  bankFeatherMetres = RIVER_BANK_TRANSITION_METRES
): number {
  return widthMetres * 0.5 + bankFeatherMetres;
}

function worldToLowerSampleIndex(worldCoordinate: number, options: RiverSegmentRasterOptions): number {
  return Math.max(
    0,
    Math.ceil(
      (worldCoordinate + options.sizeMetres * 0.5) / options.sampleSpacing - options.sampleOffset - Number.EPSILON
    )
  );
}

function worldToUpperSampleIndex(worldCoordinate: number, options: RiverSegmentRasterOptions): number {
  return Math.min(
    options.resolution - 1,
    Math.floor(
      (worldCoordinate + options.sizeMetres * 0.5) / options.sampleSpacing - options.sampleOffset + Number.EPSILON
    )
  );
}

function sampleIndexToWorld(index: number, options: RiverSegmentRasterOptions): number {
  return (index + options.sampleOffset) * options.sampleSpacing - options.sizeMetres * 0.5;
}

function normalizedDistance(
  left: Pick<SeedWorldRiverCurveCandidate, "x" | "y">,
  right: Pick<SeedWorldRiverCurveCandidate, "x" | "y">
): number {
  return Math.hypot(right.x - left.x, right.y - left.y);
}

function limitHandle(handle: readonly [number, number], maximumLength: number): SeedWorldRiverCurveHandle {
  const length = Math.hypot(handle[0], handle[1]);
  if (length <= maximumLength || length === 0) return [handle[0], handle[1]];
  const scale = maximumLength / length;
  return [handle[0] * scale, handle[1] * scale];
}

function boundHandleToWorld(
  point: Pick<SeedWorldRiverCurveCandidate, "x" | "y">,
  handle: SeedWorldRiverCurveHandle
): SeedWorldRiverCurveHandle {
  return [clamp(point.x + handle[0], 0, 1) - point.x, clamp(point.y + handle[1], 0, 1) - point.y];
}

function smoothstep(minimum: number, maximum: number, value: number): number {
  const normalized = clamp01((value - minimum) / (maximum - minimum));
  return normalized * normalized * (3 - 2 * normalized);
}

function mix(left: number, right: number, amount: number): number {
  return left + (right - left) * amount;
}

function clamp01(value: number): number {
  return clamp(value, 0, 1);
}

function clamp(value: number, minimum: number, maximum: number): number {
  return Math.min(maximum, Math.max(minimum, value));
}
