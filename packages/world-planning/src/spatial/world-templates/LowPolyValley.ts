function model(
  id: string,
  assetUrl: string,
  x: number,
  z: number,
  scale: TemplateNode["scale"],
  yaw = 0,
  footprint?: TemplateNode["footprint"]
): TemplateNode {
  return {
    id,
    assetUrl,
    position: [x, 0, z],
    scale,
    rotation: [0, yaw, 0],
    grounded: true,
    footprint,
    ...(assetUrl === mountain ? { stretchToEnvelope: true } : {})
  };
}

